const LOCAL_STORAGE_USERS_KEY = 'bid_exact_user_auth_accounts';
const LOCAL_STORAGE_SESSION_KEY = 'bid_exact_current_logged_in_user';
const LOCAL_STORAGE_CREDENTIAL_NOTICES_KEY = 'bid_exact_credential_notices';

/**
 * Get all user accounts stored in localStorage (or initialized defaults)
 */
export function getStoredUserAccounts(): UserAuthAccount[] {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_USERS_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Failed reading user accounts from localStorage', e);
  }
  // Initialize default
  localStorage.setItem(LOCAL_STORAGE_USERS_KEY, JSON.stringify(INITIAL_USER_ACCOUNTS));
  return INITIAL_USER_ACCOUNTS;
}

/**
 * Save user accounts to localStorage
 */
export function saveStoredUserAccounts(accounts: UserAuthAccount[]): void {
  try {
    localStorage.setItem(LOCAL_STORAGE_USERS_KEY, JSON.stringify(accounts));
  } catch (e) {
    console.error('Failed saving user accounts to localStorage', e);
  }
}

/**
 * Get active session user
 */
export function getActiveSessionUser(): UserAuthAccount {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_SESSION_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed && parsed.id && parsed.role) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Failed reading active session user', e);
  }
  // Default to Owner Umer Khayam
  const defaultOwner = INITIAL_USER_ACCOUNTS[0];
  localStorage.setItem(LOCAL_STORAGE_SESSION_KEY, JSON.stringify(defaultOwner));
  return defaultOwner;
}

/**
 * Set active session user
 */
export function setActiveSessionUser(user: UserAuthAccount): void {
  try {
    localStorage.setItem(LOCAL_STORAGE_SESSION_KEY, JSON.stringify(user));
  } catch (e) {
    console.error('Failed saving active session user', e);
  }
}

/**
 * Get generated credential notices
 */
export function getCredentialNotices(): GeneratedCredentialsNotice[] {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_CREDENTIAL_NOTICES_KEY);
    if (raw) {
      return JSON.parse(raw);
    }
  } catch (e) {
    console.error('Failed reading credential notices', e);
  }
  return [];
}

/**
 * Save generated credential notice
 */
export function addCredentialNotice(notice: GeneratedCredentialsNotice): void {
  try {
    const existing = getCredentialNotices();
    const updated = [notice, ...existing];
    localStorage.setItem(LOCAL_STORAGE_CREDENTIAL_NOTICES_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Failed saving credential notice', e);
  }
}

/**
 * Automatically provision credentials when an employee is registered
 */
export function provisionEmployeeLogin(employee: EmployeeItem): { user: UserAuthAccount; notice: GeneratedCredentialsNotice } {
  const username = employee.email.split('@')[0] || employee.name.toLowerCase().replace(/\s+/g, '.');
  const tempPassword = generateSecurePassword('employee', employee.id);
  
  // If HR manager or leadership, assign HR or Employee role appropriately
  const isHr = employee.department === 'Finance & Legal' && employee.role.toLowerCase().includes('hr');
  const role: UserRole = isHr ? 'hr' : 'employee';

  const user: UserAuthAccount = {
    id: `USR-${employee.id}`,
    username,
    email: employee.email,
    name: employee.name,
    role,
    title: employee.role,
    department: employee.department,
    targetId: employee.id,
    targetName: `${employee.name} (${employee.id})`,
    createdAt: new Date().toISOString().slice(0, 10),
    autoGeneratedPassword: tempPassword,
    status: 'active',
  };

  const notice: GeneratedCredentialsNotice = {
    id: `NOTIF-CRED-${Date.now()}`,
    userId: user.id,
    name: employee.name,
    email: employee.email,
    role,
    tempPassword,
    targetEntityName: `${employee.name} · ${employee.role}`,
    createdAt: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
    sentStatus: 'sent',
  };

  // Persist
  const allUsers = getStoredUserAccounts();
  const filtered = allUsers.filter(u => u.id !== user.id && u.email !== user.email);
  saveStoredUserAccounts([user, ...filtered]);
  addCredentialNotice(notice);

  return { user, notice };
}

/**
 * Automatically provision credentials when a client is registered
 */
export function provisionClientLogin(client: ClientItem): { user: UserAuthAccount; notice: GeneratedCredentialsNotice } {
  const cleanClientName = client.name.toLowerCase().replace(/[^a-z0-9]/g, '');
  const username = `${cleanClientName}.portal`;
  const email = client.contact.email || `portal@${cleanClientName}.com`;
  const tempPassword = generateSecurePassword('client', client.id);

  const user: UserAuthAccount = {
    id: `USR-${client.id}`,
    username,
    email,
    name: `${client.contact.name} (${client.name})`,
    role: 'client',
    title: client.contact.title || 'Client Pre-Construction Director',
    department: 'Enterprise Client Account',
    targetId: client.id,
    targetName: client.name,
    createdAt: new Date().toISOString().slice(0, 10),
    autoGeneratedPassword: tempPassword,
    status: 'active',
  };

  const notice: GeneratedCredentialsNotice = {
    id: `NOTIF-CRED-${Date.now()}`,
    userId: user.id,
    name: client.contact.name || client.name,
    email,
    role: 'client',
    tempPassword,
    targetEntityName: `${client.name} (Contact: ${client.contact.name})`,
    createdAt: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
    sentStatus: 'sent',
  };

  // Persist
  const allUsers = getStoredUserAccounts();
  const filtered = allUsers.filter(u => u.id !== user.id && u.email !== user.email);
  saveStoredUserAccounts([user, ...filtered]);
  addCredentialNotice(notice);

  return { user, notice };
}

/**
 * Generate a strong, secure random temporary password for newly registered users
 */
export function generateSecurePassword(role: UserRole, prefix: string): string {
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789!@#$%';
  let randomPart = '';
  for (let i = 0; i < 6; i++) {
    randomPart += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  const roleCode = role.toUpperCase().slice(0, 3);
  return `BE-${roleCode}-${prefix ? prefix.slice(0, 3).toUpperCase() : 'SEC'}-${randomPart}!`;
}

